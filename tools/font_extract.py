#!/usr/bin/env python3
"""Extract embedded-graphics ASCII font glyphs to firmware/src/fonts.cpp.

Reads the raw 1bpp font strips shipped in the embedded-graphics 0.8.2 crate
(cargo registry cache) and re-packs them per-glyph so the C++ firmware can
render pixel-identical text to the legacy Rust firmware.

Usage: python3 tools/font_extract.py
"""
import glob
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "src" / "fonts.cpp"

# (raw strip file, strip width px, char w, char h, baseline, C symbol)
FONTS = [
    ("font_6x12.raw", 96, 6, 12, 9, "font6x12"),
    ("font_9x15_bold.raw", 144, 9, 15, 11, "font9x15_bold"),
]
GLYPHS = 95  # ASCII 32..126


def find_eg_crate() -> Path:
    hits = sorted(glob.glob(os.path.expanduser(
        "~/.cargo/registry/src/*/embedded-graphics-0.8.2")))
    if not hits:
        sys.exit("embedded-graphics-0.8.2 not found in ~/.cargo/registry — "
                 "build the legacy Rust firmware once to populate the cache")
    return Path(hits[0])


def load_glyphs(eg: Path, name: str, strip_w: int, cw: int, ch: int):
    # e-g packs the glyphs as a grid: 16 glyphs per strip row
    # (strip_w / cw == 16 for both fonts used here).
    per_row = strip_w // cw
    data = (eg / "fonts" / "raw" / "ascii" / name).read_bytes()
    stride = strip_w // 8
    rows_total = (GLYPHS + per_row - 1) // per_row
    assert len(data) == rows_total * ch * stride, (
        f"{name}: strip {len(data)} bytes != {rows_total}x{ch}px grid")
    row_bytes = (cw + 7) // 8
    glyphs = []
    for i in range(GLYPHS):
        gx0 = (i % per_row) * cw
        gy0 = (i // per_row) * ch
        rows = bytearray(row_bytes * ch)
        for y in range(ch):
            for x in range(cw):
                bit = (gy0 + y) * strip_w + gx0 + x
                if data[bit // 8] & (0x80 >> (bit % 8)):
                    rows[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
        glyphs.append(bytes(rows))
    return glyphs


def emit(fonts):
    parts = [
        "// GENERATED by tools/font_extract.py from embedded-graphics 0.8.2",
        "// font data — do not edit (see fonts.h for layout).",
        "",
        '#include "fonts.h"',
        "",
    ]
    for (_, _, _, _, _, sym), glyphs in zip(FONTS, fonts):
        # sanity: digits and SINCE glyphs must contain ink, space must not
        for ch, idx in (("0", 16), ("S", 51), ("I", 41), ("N", 46), ("C", 35),
                        ("E", 37), (".", 14)):
            assert any(glyphs[idx]), f"{sym}: glyph '{ch}' unexpectedly empty"
        assert not any(glyphs[0]), f"{sym}: space glyph unexpectedly has ink"
        body = []
        for g in glyphs:
            for i in range(0, len(g), 12):
                body.append("    " + ", ".join(f"0x{b:02X}" for b in g[i:i + 12]) + ",")
        parts.append(f"const uint8_t {sym}[] = {{\n" + "\n".join(body) + "\n};\n")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


def main():
    eg = find_eg_crate()
    print("source crate:", eg)
    fonts = [load_glyphs(eg, name, w, cw, ch) for (name, w, cw, ch, _, _) in FONTS]
    emit(fonts)


if __name__ == "__main__":
    main()
